#!/usr/bin/env python3
"""ShipTheJam Game Jam Agent Kit — rules sync. AGENTS.md is the single source of truth.

  python3 sync-rules.py init --engine godot|phaser|roblox --dest ../my-game
      Install the kit into a game project (AGENTS.md = core + engine pack, roles,
      playbook, JAM.md template), then generate tool files.

  python3 sync-rules.py [PROJECT_DIR]      (default: current directory)
      Regenerate tool files from PROJECT_DIR/AGENTS.md:
        .cursor/rules/*.mdc                 (Cursor project rules)
        CLAUDE.md                           (Claude Code)
        .github/copilot-instructions.md     (Copilot, repo-wide)
        .github/instructions/*.instructions.md (Copilot, path-specific)
      Codex reads AGENTS.md natively; nothing to generate.

A '## ' section in AGENTS.md followed by '<!-- globs: a, b -->' becomes a file-scoped
rule; all other sections go into the always-on core rule. Stdlib only, no deps.
"""
import argparse, re, shutil, sys
from pathlib import Path

KIT = Path(__file__).resolve().parent
HEADER = "<!-- GENERATED by sync-rules.py from AGENTS.md. Do not edit; edit AGENTS.md and re-run. -->\n"
GLOB_RE = re.compile(r"^<!--\s*globs:\s*(.+?)\s*-->\s*$", re.M)

def slug(s): return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40]

def split_sections(text):
    """Return (preamble, [(title, body, globs|None)])."""
    parts = re.split(r"^## ", text, flags=re.M)
    pre, out = parts[0], []
    for p in parts[1:]:
        title, _, body = p.partition("\n")
        m = GLOB_RE.search(body)
        globs = [g.strip() for g in m.group(1).split(",")] if m else None
        body = GLOB_RE.sub("", body).strip("\n")
        out.append((title.strip(), body, globs))
    return pre, out

def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print("  wrote", path)

def generate(proj):
    src = proj / "AGENTS.md"
    if not src.exists(): sys.exit(f"No AGENTS.md in {proj}")
    text = src.read_text(encoding="utf-8")
    pre, secs = split_sections(text)
    core = [s for s in secs if not s[2]]
    scoped = [s for s in secs if s[2]]
    rules = proj / ".cursor" / "rules"
    if rules.exists():  # remove only our previously generated files
        for f in rules.glob("gjak-*.mdc"): f.unlink()
    core_md = "\n\n".join(f"## {t}\n{b}" for t, b, _ in core)
    write(rules / "gjak-core.mdc", f"---\nalwaysApply: true\n---\n{HEADER}\n{core_md}\n")
    for t, b, g in scoped:
        write(rules / f"gjak-{slug(t)}.mdc",
              f"---\nglobs: {', '.join(g)}\nalwaysApply: false\n---\n{HEADER}\n## {t}\n{b}\n")
    roles = proj / ".agents" / "roles"
    for r in sorted(roles.glob("*.md")) if roles.exists() else []:
        first = r.read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
        write(rules / f"gjak-role-{r.stem}.mdc",
              f"---\ndescription: \"{first}. Use when the user asks to act as {r.stem}.\"\nalwaysApply: false\n---\n"
              f"{HEADER}\nRead and follow @.agents/roles/{r.name} for this task.\n")
    write(proj / "CLAUDE.md", HEADER + "\n" + GLOB_RE.sub("", text).strip() + "\n")
    gh = proj / ".github"
    write(gh / "copilot-instructions.md", HEADER + "\n" + pre.strip() + "\n\n" + core_md + "\n")
    ins = gh / "instructions"
    if ins.exists():
        for f in ins.glob("gjak-*.instructions.md"): f.unlink()
    for t, b, g in scoped:
        write(ins / f"gjak-{slug(t)}.instructions.md",
              f"---\napplyTo: \"{','.join(g)}\"\n---\n{HEADER}\n## {t}\n{b}\n")
    print("Done. Codex/Cursor also read AGENTS.md directly.")

def init(engine, dest):
    eng = KIT / "engines" / f"{engine}.md"
    if not eng.exists():
        avail = [p.stem for p in (KIT / "engines").glob("*.md")]
        sys.exit(f"Engine '{engine}' not in this kit. Available: {', '.join(avail)}")
    dest.mkdir(parents=True, exist_ok=True)
    if (dest / "AGENTS.md").exists():
        sys.exit(f"{dest/'AGENTS.md'} exists. Merge by hand or delete it, then re-run.")
    write(dest / "AGENTS.md", (KIT / "AGENTS.md").read_text().rstrip() + "\n\n" + eng.read_text())
    for sub in ("roles", "playbook"):
        if (KIT / sub).exists():
            shutil.copytree(KIT / sub, dest / ".agents" / sub, dirs_exist_ok=True)
    if not (dest / "JAM.md").exists() and (KIT / "templates" / "JAM.md").exists():
        shutil.copy(KIT / "templates" / "JAM.md", dest / "JAM.md")
    generate(dest)

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "init":
        ap = argparse.ArgumentParser(prog="sync-rules.py init")
        ap.add_argument("--engine", required=True)
        ap.add_argument("--dest", required=True, type=Path)
        a = ap.parse_args(sys.argv[2:])
        init(a.engine, a.dest.resolve())
    else:
        generate(Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve())
